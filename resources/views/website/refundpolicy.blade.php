    <script>
        (function () {

            /*==========================================
                SCROLL-REVEAL ANIMATION
            ==========================================*/

            const fadeEls = document.querySelectorAll("[data-fade]");

            if ("IntersectionObserver" in window && fadeEls.length) {

                const observer = new IntersectionObserver(function (entries, obs) {
                    entries.forEach(function (entry) {
                        if (entry.isIntersecting) {
                            entry.target.classList.add("return-refund-policy-visible");
                            obs.unobserve(entry.target);
                        }
                    });
                }, { threshold: 0.12, rootMargin: "0px 0px -30px 0px" });

                fadeEls.forEach(function (el) {
                    el.classList.add("return-refund-policy-fade");
                    observer.observe(el);
                });

            } else {

                fadeEls.forEach(function (el) {
                    el.classList.add("return-refund-policy-visible");
                });

            }

            /*==========================================
                CONTACT SUPPORT — CLICK RIPPLE
            ==========================================*/

            const supportBtn = document.querySelector(".return-refund-policy-support-btn");

            if (supportBtn) {

                supportBtn.addEventListener("click", function (e) {

                    const ripple = document.createElement("span");
                    ripple.className = "return-refund-policy-ripple";

                    const rect = this.getBoundingClientRect();
                    const size = Math.max(rect.width, rect.height);

                    ripple.style.width = ripple.style.height = size + "px";
                    ripple.style.left = (e.clientX - rect.left - size / 2) + "px";
                    ripple.style.top = (e.clientY - rect.top - size / 2) + "px";

                    this.appendChild(ripple);

                    setTimeout(function () {
                        ripple.remove();
                    }, 650);

                });

            }

            /*==========================================
                FEATURE STRIP ICON — CLICK PULSE
            ==========================================*/

            document.querySelectorAll(".return-refund-policy-feature-icon, .return-refund-policy-item-icon").forEach(function (icon) {

                icon.addEventListener("click", function () {
                    this.classList.remove("return-refund-policy-icon-pop");
                    void this.offsetWidth;
                    this.classList.add("return-refund-policy-icon-pop");
                });

            });

        })();
    </script>

